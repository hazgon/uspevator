let appLanguage = 'en';

function normalizeLanguage(choice) {
  return choice === 'en' || choice === 'ru' ? choice : 'system';
}

function resolveLanguage(choice, systemLocale) {
  const setting = normalizeLanguage(choice);
  if (setting !== 'system') return setting;
  return /^ru(?:[-_]|$)/i.test(systemLocale || '') ? 'ru' : 'en';
}

function t(message, ...values) {
  const source = typeof message === 'string' ? message : message.reduce((key, part, index) =>
    key + (index ? '{' + (index - 1) + '}' : '') + part, '');
  const translated = appLanguage === 'en' && Object.prototype.hasOwnProperty.call(ENGLISH, source) ? ENGLISH[source] : source;
  return values.length ? translated.replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)])) : translated;
}

// Capture only the authored shell, before any task or template content is rendered.
function shellTranslations() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const textNodes = [];
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('script, style')) continue;
    const source = node.nodeValue.trim();
    if (!Object.prototype.hasOwnProperty.call(ENGLISH, source)) continue;
    const offset = node.nodeValue.indexOf(source);
    textNodes.push({node, source, before: node.nodeValue.slice(0, offset), after: node.nodeValue.slice(offset + source.length)});
  }
  const attributeNames = ['aria-label', 'title', 'placeholder'];
  const elements = document.querySelectorAll(attributeNames.map(name => '[' + name + ']').join(','));
  const attributes = [];
  for (const element of elements) {
    for (const name of attributeNames) {
      const source = element.getAttribute(name);
      if (source !== null && Object.prototype.hasOwnProperty.call(ENGLISH, source)) attributes.push({element, name, source});
    }
  }
  return () => {
    document.documentElement.lang = appLanguage;
    document.title = t('Успеватор');
    for (const {node, source, before, after} of textNodes) node.nodeValue = before + t(source) + after;
    for (const {element, name, source} of attributes) element.setAttribute(name, t(source));
  };
}
